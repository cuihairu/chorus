using System.Text.Json;
using System.Data;
using System.Data.Common;
using Microsoft.Data.Sqlite;
using Npgsql;

namespace Chorus.Control;

public enum ControlDatabaseProvider { Sqlite, PostgreSql }

/// <summary>Transactional authority store. SQLite is for local/single-host use; PostgreSQL supports multi-worker deployment.</summary>
public sealed class ControlDatabase
{
    public static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);
    private readonly string _connectionString;
    private readonly ControlDatabaseProvider _provider;
    public ControlDatabase(string connection, ControlDatabaseProvider provider = ControlDatabaseProvider.Sqlite)
    {
        _provider = provider;
        if (provider == ControlDatabaseProvider.Sqlite)
        {
            var path = Path.GetFullPath(connection);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            _connectionString = new SqliteConnectionStringBuilder { DataSource = path, DefaultTimeout = 10 }.ToString();
        }
        else _connectionString = connection;
        using var db = Open();
        using var cmd = db.CreateCommand();
        cmd.CommandText = provider == ControlDatabaseProvider.Sqlite ? """
            PRAGMA journal_mode=WAL;
            PRAGMA synchronous=FULL;
            CREATE TABLE IF NOT EXISTS records(kind TEXT NOT NULL, id TEXT NOT NULL, body TEXT NOT NULL, PRIMARY KEY(kind,id));
            CREATE TABLE IF NOT EXISTS room_events(room_id TEXT NOT NULL, event_key TEXT NOT NULL, body TEXT NOT NULL, at INTEGER NOT NULL, PRIMARY KEY(room_id,event_key));
            CREATE INDEX IF NOT EXISTS ix_room_events_order ON room_events(room_id,at,event_key);
            CREATE TABLE IF NOT EXISTS event_receipts(room_id TEXT NOT NULL, event_key TEXT NOT NULL, at INTEGER NOT NULL, PRIMARY KEY(room_id,event_key));
            CREATE INDEX IF NOT EXISTS ix_event_receipts_ttl ON event_receipts(room_id,at);
            CREATE TABLE IF NOT EXISTS room_queue_counts(room_id TEXT PRIMARY KEY, pending INTEGER NOT NULL DEFAULT 0, receipts INTEGER NOT NULL DEFAULT 0);
            CREATE TABLE IF NOT EXISTS event_heat(bucket_at INTEGER NOT NULL, room_id TEXT NOT NULL, platform TEXT NOT NULL, kind INTEGER NOT NULL, events INTEGER NOT NULL, gift_units INTEGER NOT NULL, PRIMARY KEY(bucket_at,room_id,platform,kind));
            CREATE INDEX IF NOT EXISTS ix_event_heat_bucket ON event_heat(bucket_at);
            CREATE TABLE IF NOT EXISTS event_heat_alert_ack(bucket_at INTEGER NOT NULL, platform TEXT NOT NULL, actor TEXT NOT NULL, at INTEGER NOT NULL, PRIMARY KEY(bucket_at,platform));
            CREATE TABLE IF NOT EXISTS checkpoints(room_id TEXT PRIMARY KEY, body TEXT NOT NULL, tick_id INTEGER NOT NULL, epoch INTEGER NOT NULL, checksum INTEGER NOT NULL, schema_version INTEGER NOT NULL);
            CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY AUTOINCREMENT, at INTEGER NOT NULL, actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL, detail TEXT NOT NULL);
            """ : """
            CREATE TABLE IF NOT EXISTS records(kind TEXT NOT NULL, id TEXT NOT NULL, body TEXT NOT NULL, PRIMARY KEY(kind,id));
            CREATE TABLE IF NOT EXISTS room_events(room_id TEXT NOT NULL, event_key TEXT NOT NULL, body TEXT NOT NULL, at BIGINT NOT NULL, PRIMARY KEY(room_id,event_key));
            CREATE INDEX IF NOT EXISTS ix_room_events_order ON room_events(room_id,at,event_key);
            CREATE TABLE IF NOT EXISTS event_receipts(room_id TEXT NOT NULL, event_key TEXT NOT NULL, at BIGINT NOT NULL, PRIMARY KEY(room_id,event_key));
            CREATE INDEX IF NOT EXISTS ix_event_receipts_ttl ON event_receipts(room_id,at);
            CREATE TABLE IF NOT EXISTS room_queue_counts(room_id TEXT PRIMARY KEY, pending INTEGER NOT NULL DEFAULT 0, receipts INTEGER NOT NULL DEFAULT 0);
            CREATE TABLE IF NOT EXISTS event_heat(bucket_at BIGINT NOT NULL, room_id TEXT NOT NULL, platform TEXT NOT NULL, kind INTEGER NOT NULL, events BIGINT NOT NULL, gift_units BIGINT NOT NULL, PRIMARY KEY(bucket_at,room_id,platform,kind));
            CREATE INDEX IF NOT EXISTS ix_event_heat_bucket ON event_heat(bucket_at);
            CREATE TABLE IF NOT EXISTS event_heat_alert_ack(bucket_at BIGINT NOT NULL, platform TEXT NOT NULL, actor TEXT NOT NULL, at BIGINT NOT NULL, PRIMARY KEY(bucket_at,platform));
            CREATE TABLE IF NOT EXISTS checkpoints(room_id TEXT PRIMARY KEY, body TEXT NOT NULL, tick_id BIGINT NOT NULL, epoch BIGINT NOT NULL, checksum BIGINT NOT NULL, schema_version INTEGER NOT NULL);
            CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at BIGINT NOT NULL, actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL, detail TEXT NOT NULL);
            """;
        cmd.ExecuteNonQuery();
    }
    private DbConnection Open()
    {
        DbConnection db = _provider switch
        {
            ControlDatabaseProvider.Sqlite => new SqliteConnection(_connectionString),
            ControlDatabaseProvider.PostgreSql => new NpgsqlConnection(_connectionString),
            _ => throw new ArgumentOutOfRangeException(nameof(_provider))
        };
        db.Open();
        return db;
    }
    private DbTransaction Begin(DbConnection db, bool write, IsolationLevel? isolation = null) => db is SqliteConnection sqlite
        ? sqlite.BeginTransaction(deferred: !write)
        : db.BeginTransaction(isolation ?? (write ? IsolationLevel.Serializable : IsolationLevel.ReadCommitted));
    public T Read<T>(Func<Transaction, T> query)
    {
        using var db = Open();
        using var transaction = Begin(db, write: false);
        return query(new Transaction(db, transaction, _provider == ControlDatabaseProvider.PostgreSql));
    }
    public T Write<T>(Func<Transaction, T> change)
        => Write(change, IsolationLevel.Serializable);
    public T WriteRoom<T>(Func<Transaction, T> change)
        => Write(change, IsolationLevel.ReadCommitted);
    private T Write<T>(Func<Transaction, T> change, IsolationLevel isolation)
    {
        for (var attempt = 0; ; attempt++)
        {
            try
            {
                using var db = Open();
                using var transaction = Begin(db, write: true, isolation);
                var result = change(new Transaction(db, transaction, _provider == ControlDatabaseProvider.PostgreSql));
                transaction.Commit();
                return result;
            }
            catch (PostgresException ex) when (attempt < 3 && ex.SqlState is PostgresErrorCodes.SerializationFailure or PostgresErrorCodes.DeadlockDetected)
            {
                Thread.Sleep(2 << attempt);
            }
        }
    }
    public sealed class Transaction(DbConnection db, DbTransaction transaction, bool postgres)
    {
        private DbCommand Command(string sql, params (string Name, object? Value)[] parameters)
        {
            var cmd = db.CreateCommand();
            cmd.Transaction = transaction;
            cmd.CommandText = sql;
            foreach (var (name, value) in parameters)
            {
                var parameter = cmd.CreateParameter();
                parameter.ParameterName = name;
                parameter.Value = value ?? DBNull.Value;
                cmd.Parameters.Add(parameter);
            }
            return cmd;
        }
        public T? Get<T>(string kind, string id)
        {
            using var cmd = Command("SELECT body FROM records WHERE kind=@k AND id=@i", ("@k", kind), ("@i", id));
            return cmd.ExecuteScalar() is string body ? JsonSerializer.Deserialize<T>(body, Json) : default;
        }
        public T? GetForUpdate<T>(string kind, string id)
        {
            using var cmd = Command("SELECT body FROM records WHERE kind=@k AND id=@i" + (postgres ? " FOR UPDATE" : string.Empty),
                ("@k", kind), ("@i", id));
            return cmd.ExecuteScalar() is string body ? JsonSerializer.Deserialize<T>(body, Json) : default;
        }
        public List<T> List<T>(string kind)
        {
            using var cmd = Command("SELECT body FROM records WHERE kind=@k ORDER BY id", ("@k", kind));
            using var reader = cmd.ExecuteReader();
            List<T> result = [];
            while (reader.Read()) result.Add(JsonSerializer.Deserialize<T>(reader.GetString(0), Json)!);
            return result;
        }
        public void Put<T>(string kind, string id, T value)
        {
            if (kind == "room" && value is RoomRecord room)
                value = (T)(object)(room with { Inbox = null, Receipts = null, Snapshot = null });
            using var cmd = Command("INSERT INTO records(kind,id,body) VALUES(@k,@i,@b) ON CONFLICT(kind,id) DO UPDATE SET body=excluded.body", ("@k", kind), ("@i", id), ("@b", JsonSerializer.Serialize(value, Json)));
            cmd.ExecuteNonQuery();
        }
        public int PendingCount(string roomId)
        {
            using var cmd = Command("SELECT pending FROM room_queue_counts WHERE room_id=@r", ("@r", roomId));
            return Convert.ToInt32(cmd.ExecuteScalar() ?? 0);
        }
        public List<Chorus.Protocol.Models.AudienceEvent> PendingEvents(string roomId, int limit)
        {
            using var cmd = Command("SELECT body FROM room_events WHERE room_id=@r ORDER BY at,event_key LIMIT @n", ("@r", roomId), ("@n", Math.Clamp(limit,1,8000)));
            using var reader = cmd.ExecuteReader();
            List<Chorus.Protocol.Models.AudienceEvent> result = [];
            while(reader.Read()) result.Add(JsonSerializer.Deserialize<Chorus.Protocol.Models.AudienceEvent>(reader.GetString(0), Json)!);
            return result;
        }
        public bool AddEvent(string roomId, string key, Chorus.Protocol.Models.AudienceEvent value, long at)
        {
            if (postgres)
            {
                var pgBucket = at - at % 60_000;
                var pgGiftUnits = value.Kind == Chorus.Protocol.Models.AudienceEventKind.Gift ? Math.Max(0, value.GiftCount ?? 0) : 0;
                using var pgCommand = Command("""
                    WITH receipt_added AS (
                        INSERT INTO event_receipts(room_id,event_key,at) VALUES(@r,@k,@a)
                        ON CONFLICT(room_id,event_key) DO NOTHING
                        RETURNING event_key
                    ), capacity_bumped AS (
                        INSERT INTO room_queue_counts(room_id,pending,receipts)
                        SELECT @r,1,1 FROM receipt_added WHERE TRUE
                        ON CONFLICT(room_id) DO UPDATE SET pending=room_queue_counts.pending+1,receipts=room_queue_counts.receipts+1
                        WHERE room_queue_counts.receipts<100000
                        RETURNING room_id
                    ), event_added AS (
                        INSERT INTO room_events(room_id,event_key,body,at)
                        SELECT @r,@k,@b,@a FROM capacity_bumped
                        RETURNING event_key
                    ), heat_added AS (
                        INSERT INTO event_heat(bucket_at,room_id,platform,kind,events,gift_units)
                        SELECT @bucket,@r,@p,@kind,1,@g FROM event_added
                        ON CONFLICT(bucket_at,room_id,platform,kind) DO UPDATE
                        SET events=event_heat.events+1,gift_units=event_heat.gift_units+excluded.gift_units
                    )
                    SELECT EXISTS(SELECT 1 FROM receipt_added), EXISTS(SELECT 1 FROM capacity_bumped)
                    """, ("@r", roomId), ("@k", key), ("@a", at), ("@b", JsonSerializer.Serialize(value, Json)),
                    ("@bucket", pgBucket), ("@p", ControlDimensions.PlatformBucket(value.Platform)), ("@kind", (int)value.Kind), ("@g", pgGiftUnits));
                using var reader = pgCommand.ExecuteReader();
                if (!reader.Read()) throw new InvalidOperationException("PostgreSQL event insertion returned no outcome.");
                var receiptAdded = reader.GetBoolean(0);
                var capacityAvailable = reader.GetBoolean(1);
                if (receiptAdded && !capacityAvailable)
                    throw new ControlConflictException("Room receipt capacity reached; retry after dedup window.");
                return receiptAdded;
            }

            using var receipt = Command("INSERT INTO event_receipts(room_id,event_key,at) VALUES(@r,@k,@a) ON CONFLICT(room_id,event_key) DO NOTHING", ("@r",roomId), ("@k",key), ("@a",at));
            if(receipt.ExecuteNonQuery() == 0) return false;
            using var bump = Command("INSERT INTO room_queue_counts(room_id,pending,receipts) VALUES(@r,1,1) " +
                "ON CONFLICT(room_id) DO UPDATE SET pending=room_queue_counts.pending+1,receipts=room_queue_counts.receipts+1 " +
                "WHERE room_queue_counts.receipts<100000 RETURNING receipts",("@r",roomId));
            if (bump.ExecuteScalar() is null) throw new ControlConflictException("Room receipt capacity reached; retry after dedup window.");
            using var cmd = Command("INSERT INTO room_events(room_id,event_key,body,at) VALUES(@r,@k,@b,@a)", ("@r",roomId), ("@k",key), ("@b",JsonSerializer.Serialize(value,Json)), ("@a",at));
            cmd.ExecuteNonQuery();
            var bucket = at - at % 60_000;
            var giftUnits = value.Kind == Chorus.Protocol.Models.AudienceEventKind.Gift ? Math.Max(0, value.GiftCount ?? 0) : 0;
            using var heat = Command("INSERT INTO event_heat(bucket_at,room_id,platform,kind,events,gift_units) VALUES(@b,@r,@p,@k,1,@g) " +
                "ON CONFLICT(bucket_at,room_id,platform,kind) DO UPDATE SET events=event_heat.events+1,gift_units=event_heat.gift_units+excluded.gift_units",
                ("@b",bucket), ("@r",roomId), ("@p",ControlDimensions.PlatformBucket(value.Platform)), ("@k",(int)value.Kind), ("@g",giftUnits));
            heat.ExecuteNonQuery();
            return true;
        }
        public List<EventHeatSample> EventHeat(long sinceMs)
        {
            using var cmd = Command("SELECT bucket_at,platform,kind,SUM(events),SUM(gift_units) FROM event_heat WHERE bucket_at>=@s GROUP BY bucket_at,platform,kind ORDER BY bucket_at,platform,kind", ("@s", sinceMs - sinceMs % 60_000));
            using var reader = cmd.ExecuteReader();
            List<EventHeatSample> result = [];
            while (reader.Read()) result.Add(new(reader.GetInt64(0), reader.GetString(1), (Chorus.Protocol.Models.AudienceEventKind)reader.GetInt32(2), reader.GetInt64(3), reader.GetInt64(4)));
            return result;
        }
        public List<EventHeatAlert> EventHeatAlerts(long sinceMs, long threshold)
        {
            using var cmd = Command("SELECT h.bucket_at,h.platform,SUM(h.events),a.at FROM event_heat h " +
                "LEFT JOIN event_heat_alert_ack a ON a.bucket_at=h.bucket_at AND a.platform=h.platform " +
                "WHERE h.bucket_at>=@s GROUP BY h.bucket_at,h.platform,a.at HAVING SUM(h.events)>=@t ORDER BY h.bucket_at DESC,h.platform",
                ("@s", sinceMs - sinceMs % 60_000), ("@t", threshold));
            using var reader = cmd.ExecuteReader();
            List<EventHeatAlert> result = [];
            while (reader.Read())
            {
                var bucket = reader.GetInt64(0);
                var platform = reader.GetString(1);
                var events = reader.GetInt64(2);
                long? acknowledgedAt = reader.IsDBNull(3) ? null : reader.GetInt64(3);
                result.Add(new($"{platform}:{bucket}", platform, bucket, events, threshold, acknowledgedAt is not null, acknowledgedAt));
            }
            return result;
        }
        public long EventHeatCount(long bucketAtMs, string platform)
        {
            using var cmd = Command("SELECT COALESCE(SUM(events),0) FROM event_heat WHERE bucket_at=@b AND platform=@p", ("@b", bucketAtMs), ("@p", platform));
            return Convert.ToInt64(cmd.ExecuteScalar() ?? 0L);
        }
        public (bool Inserted, long AtMs) AcknowledgeEventHeat(long bucketAtMs, string platform, string actor, long atMs)
        {
            using var cmd = Command("INSERT INTO event_heat_alert_ack(bucket_at,platform,actor,at) VALUES(@b,@p,@a,@n) ON CONFLICT(bucket_at,platform) DO NOTHING",
                ("@b", bucketAtMs), ("@p", platform), ("@a", actor), ("@n", atMs));
            var inserted = cmd.ExecuteNonQuery() > 0;
            using var read = Command("SELECT at FROM event_heat_alert_ack WHERE bucket_at=@b AND platform=@p", ("@b", bucketAtMs), ("@p", platform));
            return (inserted, Convert.ToInt64(read.ExecuteScalar()));
        }
        public int PruneEventHeat(long cutoffMs)
        {
            var cutoff = cutoffMs - cutoffMs % 60_000;
            using var ack = Command("DELETE FROM event_heat_alert_ack WHERE bucket_at<@c", ("@c", cutoff));
            ack.ExecuteNonQuery();
            using var cmd = Command("DELETE FROM event_heat WHERE bucket_at<@c", ("@c", cutoff));
            return cmd.ExecuteNonQuery();
        }
        public bool ReceiptExists(string roomId,string key)
        {
            using var cmd=Command("SELECT 1 FROM event_receipts WHERE room_id=@r AND event_key=@k",("@r",roomId),("@k",key)); return cmd.ExecuteScalar() is not null;
        }
        public bool ReceiptsExist(string roomId, IReadOnlyCollection<string> keys)
        {
            if (keys.Count == 0) return true;
            using var cmd = postgres
                ? Command("SELECT COUNT(*) FROM event_receipts WHERE room_id=@r AND event_key=ANY(@keys)", ("@r", roomId), ("@keys", keys.ToArray()))
                : Command("SELECT COUNT(*) FROM event_receipts WHERE room_id=@r AND event_key IN (SELECT value FROM json_each(@keys))", ("@r", roomId), ("@keys", JsonSerializer.Serialize(keys, Json)));
            return Convert.ToInt64(cmd.ExecuteScalar() ?? 0L) == keys.Count;
        }
        public bool TryConsumeEvents(string roomId, IReadOnlyCollection<string> keys)
        {
            if (keys.Count == 0) return true;
            if (!postgres)
            {
                if (!ReceiptsExist(roomId, keys)) return false;
                DeleteEvents(roomId, keys.ToArray());
                return true;
            }

            using var cmd = Command("""
                WITH receipt_status AS MATERIALIZED (
                    SELECT COUNT(*) = cardinality(@keys)::bigint AS valid
                    FROM event_receipts WHERE room_id=@r AND event_key=ANY(@keys)
                ), deleted_events AS (
                    DELETE FROM room_events e USING receipt_status s
                    WHERE s.valid AND e.room_id=@r AND e.event_key=ANY(@keys)
                    RETURNING 1
                ), pending_updated AS (
                    UPDATE room_queue_counts q
                    SET pending=GREATEST(0,q.pending-(SELECT COUNT(*)::integer FROM deleted_events))
                    WHERE q.room_id=@r AND EXISTS(SELECT 1 FROM deleted_events)
                    RETURNING q.pending
                )
                SELECT valid FROM receipt_status
                """, ("@r", roomId), ("@keys", keys.ToArray()));
            return cmd.ExecuteScalar() is true;
        }
        public void PruneReceipts(string roomId,long cutoff)
        {
            using var cmd=Command("DELETE FROM event_receipts WHERE room_id=@r AND at<@c AND NOT EXISTS(SELECT 1 FROM room_events e WHERE e.room_id=event_receipts.room_id AND e.event_key=event_receipts.event_key)",("@r",roomId),("@c",cutoff)); var removed=cmd.ExecuteNonQuery();
            if(removed>0){using var dec=Command("UPDATE room_queue_counts SET receipts=CASE WHEN receipts>@n THEN receipts-@n ELSE 0 END WHERE room_id=@r",("@n",removed),("@r",roomId));dec.ExecuteNonQuery();}
        }
        public void PutCheckpoint(string roomId, JsonElement state, long tick, long epoch, long checksum, int schema)
        {
            using var cmd=Command("INSERT INTO checkpoints(room_id,body,tick_id,epoch,checksum,schema_version) VALUES(@r,@b,@t,@e,@c,@s) ON CONFLICT(room_id) DO UPDATE SET body=excluded.body,tick_id=excluded.tick_id,epoch=excluded.epoch,checksum=excluded.checksum,schema_version=excluded.schema_version",("@r",roomId),("@b",state.GetRawText()),("@t",tick),("@e",epoch),("@c",checksum),("@s",schema)); cmd.ExecuteNonQuery();
        }
        public (JsonElement State,long Tick,long Epoch,long Checksum,int Schema)? GetCheckpoint(string roomId)
        {
            using var cmd=Command("SELECT body,tick_id,epoch,checksum,schema_version FROM checkpoints WHERE room_id=@r",("@r",roomId));
            using var r=cmd.ExecuteReader(); if(!r.Read()) return null;
            return (JsonDocument.Parse(r.GetString(0)).RootElement.Clone(),r.GetInt64(1),r.GetInt64(2),r.GetInt64(3),r.GetInt32(4));
        }
        public void DeleteEvents(string roomId,IReadOnlyList<string> keys)
        {
            if (keys.Count == 0) return;
            using var cmd = postgres
                ? Command("DELETE FROM room_events WHERE room_id=@r AND event_key=ANY(@keys)", ("@r", roomId), ("@keys", keys.ToArray()))
                : Command("DELETE FROM room_events WHERE room_id=@r AND event_key IN (SELECT value FROM json_each(@keys))", ("@r", roomId), ("@keys", JsonSerializer.Serialize(keys, Json)));
            var removed=cmd.ExecuteNonQuery();
            if(removed>0){using var dec=Command("UPDATE room_queue_counts SET pending=CASE WHEN pending>@n THEN pending-@n ELSE 0 END WHERE room_id=@r",("@n",removed),("@r",roomId));dec.ExecuteNonQuery();}
        }
        public void Delete(string kind, string id)
        {
            using var cmd = Command("DELETE FROM records WHERE kind=@k AND id=@i", ("@k", kind), ("@i", id));
            cmd.ExecuteNonQuery();
        }
        public void Audit(long now, string actor, string action, string target, object detail)
        {
            using var cmd = Command("INSERT INTO audit(at,actor,action,target,detail) VALUES(@n,@a,@x,@t,@d)",
                ("@n", now), ("@a", actor), ("@x", action), ("@t", target), ("@d", JsonSerializer.Serialize(detail, Json)));
            cmd.ExecuteNonQuery();
        }
        public List<AuditRecord> Audits(int limit)
        {
            using var cmd = Command("SELECT id,at,actor,action,target,detail FROM audit ORDER BY id DESC LIMIT @n", ("@n", Math.Clamp(limit, 1, 500)));
            using var r = cmd.ExecuteReader();
            List<AuditRecord> result = [];
            while (r.Read()) result.Add(new(r.GetInt64(0),r.GetInt64(1),r.GetString(2),r.GetString(3),r.GetString(4),r.GetString(5)));
            return result;
        }
        public (long Rows, long ApproximatePayloadBytes, long? OldestAtMs, long? NewestAtMs) AuditUsage()
        {
            using var cmd = Command("SELECT COUNT(*),COALESCE(SUM((LENGTH(actor)+LENGTH(action)+LENGTH(target)+LENGTH(detail))*4+32),0),MIN(at),MAX(at) FROM audit");
            using var r = cmd.ExecuteReader();
            if (!r.Read()) return (0, 0, null, null);
            return (r.GetInt64(0), r.GetInt64(1), r.IsDBNull(2) ? null : r.GetInt64(2), r.IsDBNull(3) ? null : r.GetInt64(3));
        }
    }
}
